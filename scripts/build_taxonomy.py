"""Build src/bil_mcp/data/ncbi_taxonomy.yaml from NCBI Taxonomy.

Reads the taxon IDs in species_map.yaml (curated), fetches each organism's names, synonyms and full
lineage from NCBI E-utilities, then fetches every ancestor too so group names like "rodents" or
"insects" work. Everything in the output comes from NCBI; nothing is hand-written.

Run after any change to species_map.yaml:  uv run python scripts/build_taxonomy.py
"""
from __future__ import annotations

import datetime as dt
import time
import xml.etree.ElementTree as ET
from pathlib import Path

import httpx
import yaml

DATA = Path(__file__).resolve().parents[1] / "src" / "bil_mcp" / "data"
EFETCH = "https://eutils.ncbi.nlm.nih.gov/entrez/eutils/efetch.fcgi"


def efetch(ids: list[int]) -> list[ET.Element]:
    """NCBI taxonomy records for many IDs (POST, so the ID list can be long)."""
    taxa = []
    for i in range(0, len(ids), 200):
        r = httpx.post(EFETCH, data={"db": "taxonomy", "id": ",".join(map(str, ids[i:i + 200]))}, timeout=60)
        r.raise_for_status()
        taxa += ET.fromstring(r.text).findall("Taxon")
        time.sleep(0.4)  # NCBI allows 3 requests/s without an API key
    return taxa


def names(t: ET.Element) -> dict:
    on = t.find("OtherNames")
    pick = lambda *tags: sorted({e.text for tag in tags for e in on.findall(tag)}) if on is not None else []
    return {"common_names": pick("GenbankCommonName", "CommonName"), "synonyms": pick("Synonym")}


def main() -> None:
    curated = yaml.safe_load((DATA / "species_map.yaml").read_text())
    holding_ids = sorted(int(k) for k in curated["organisms"])

    taxa: dict[int, dict] = {}
    ancestor_ids: set[int] = set()
    for t in efetch(holding_ids):
        tid = int(t.findtext("TaxId"))
        lineage = [int(a.findtext("TaxId")) for a in t.find("LineageEx")]
        ancestor_ids.update(lineage)
        taxa[tid] = {"scientific_name": t.findtext("ScientificName"), "rank": t.findtext("Rank"),
                     **names(t), "lineage": lineage}
    missing = set(holding_ids) - set(taxa)
    if missing:
        raise SystemExit(f"NCBI returned nothing for curated taxon IDs {sorted(missing)}")

    for t in efetch(sorted(ancestor_ids - set(taxa))):
        taxa[int(t.findtext("TaxId"))] = {"scientific_name": t.findtext("ScientificName"),
                                          "rank": t.findtext("Rank"), **names(t)}

    header = (f"# GENERATED by scripts/build_taxonomy.py from NCBI Taxonomy (E-utilities efetch) on "
              f"{dt.date.today().isoformat()}.\n# Do not edit: every value below comes from NCBI. "
              f"To change what BIL holds, edit species_map.yaml and rerun the script.\n"
              f"# taxa: {len(holding_ids)} BIL organisms (with lineage) + {len(taxa) - len(holding_ids)} ancestors.\n")
    body = yaml.safe_dump({"source": "https://www.ncbi.nlm.nih.gov/taxonomy",
                           "generated": dt.date.today().isoformat(),
                           "taxa": dict(sorted(taxa.items()))}, sort_keys=False, allow_unicode=True, width=120)
    (DATA / "ncbi_taxonomy.yaml").write_text(header + body)
    print(f"wrote {DATA / 'ncbi_taxonomy.yaml'}: {len(holding_ids)} organisms, {len(taxa) - len(holding_ids)} ancestors")


if __name__ == "__main__":
    main()
